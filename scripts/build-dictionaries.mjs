const en = JSON.parse(fs.readFileSync(path.join(dictDir, 'en.json'), 'utf8'));

// Helper to deeply merge with fallback to English
function buildDict(overrides) {
  const result = JSON.parse(JSON.stringify(en));
  for (const section in overrides) {
    if (result[section]) {
      result[section] = { ...result[section], ...overrides[section] };
    }
  }
  return result;
}

